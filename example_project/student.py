class Student:
    """
    Represents a student.

    Attributes:
        name (str): Student's name.
        age (int): Student's age.
    """

    def __init__(self, name, age):
        """
        Initialize a new student.

        Args:
            name (str): Student's name.
            age (int): Student's age.
        """
        self.name = name
        self.age = age