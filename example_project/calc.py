def add(a, b):
    """
    Add two numbers.

    Args:
        a (int or float): First number.
        b (int or float): Second number.

    Returns:
        int or float: Sum of a and b.
    """
    return a + b


def subtract(a, b):
    """
    Subtract two numbers.

    Args:
        a (int or float): First number.
        b (int or float): Second number.

    Returns:
        int or float: Result of a - b.
    """
    return a - b